def parse_include_list(value: str) -> list[str]:
    """解析可选交付物名称，并拒绝未知名称。"""
    names = [name.strip() for name in value.split(",") if name.strip()]
    unknown = sorted(set(names) - OPTIONAL_TEMPLATES.keys())
    if unknown:
        valid = "、".join(OPTIONAL_TEMPLATES)
        raise argparse.ArgumentTypeError(
            f"不支持的交付物：{'、'.join(unknown)}。可选值：{valid}。"
        )
    return list(dict.fromkeys(names))


def parse_args() -> argparse.Namespace:
    """解析项目目录、可选交付物和覆盖授权。"""
    parser = argparse.ArgumentParser(description="按阶段初始化 Phaser 4 游戏协作文档")
    parser.add_argument("--project-root", required=True, type=Path, help="目标游戏项目根目录")
    parser.add_argument("--work-item", required=True, type=Path, help="已 bootstrap 的 Work Item")
    parser.add_argument("--ledger", required=True, type=Path, help="Approval Ledger")
    parser.add_argument("--object", required=True, help="与 A1 审批完全一致的初始化对象")
    parser.add_argument(
        "--include",
        type=parse_include_list,
        help="逗号分隔的可选交付物：balance、assets、qa、platform、release",
    )
    parser.add_argument("--force", action="store_true", help="明确覆盖本次选择的同名文档")
    return parser.parse_args()


def validate_project_root(project_root: Path) -> Path:
    """拒绝文件系统根目录，降低误写入过宽目录的风险。"""
    resolved = project_root.resolve()
    if resolved == resolved.parent:
        raise ValueError("项目目录不能是文件系统根目录。")
    return resolved


def select_templates(include: list[str] | None) -> dict[str, str]:
    """选择核心模板，或合并每个 include 对应的多个文件。"""
    if include is None:
        return dict(CORE_TEMPLATES)

    selected: dict[str, str] = {}
    for name in include:
        # 一个 include 可以展开为多个文件；先完整收集目标，才能原子地执行覆盖检查。
        selected.update(OPTIONAL_TEMPLATES[name])
    return selected


def initialize_documents(
    project_root: Path, templates: dict[str, str], force: bool
) -> list[Path]:
    """只创建已通过 A1 preflight 的领域文档，并在写入前统一检查覆盖冲突。"""
    docs_dir = project_root / "docs"
    targets = [
        project_root / filename if filename.startswith(".workflow-control/")
        else docs_dir / filename
        for filename in templates
    ]
    existing = [path for path in targets if path.exists()]
    if existing and not force:
        names = "、".join(path.name for path in existing)
        raise FileExistsError(f"拒绝覆盖已有文档：{names}。如确需覆盖，请显式传入 --force。")

    for filename, path in zip(templates, targets, strict=True):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(templates[filename], encoding="utf-8")
    return targets


def run_preflight(
    project_root: Path,
    work_item: Path,
    ledger: Path,
    approval_object: str,
    templates: dict[str, str],
) -> None:
    """调用唯一控制 CLI 验证 A1 审批，拒绝 initializer 自行 bootstrap。"""
    cli = (
        Path(__file__).resolve().parents[2]
        / "phaser4-game-workflow-control"
        / "scripts"
        / "workflow-control.mjs"
    )
    if not cli.is_file():
        raise FileNotFoundError(f"找不到全局控制 CLI：{cli}")
    command = [
        "node",
        str(cli),
        "preflight",
        "--repo",
        str(project_root),
        "--work-item",
        str(work_item.resolve()),
        "--ledger",
        str(ledger.resolve()),
        "--action-level",
        "A1",
        "--action-type",
        "document-candidate",
        "--gate",
        "F0",
        "--object",
        approval_object,
    ]
    for filename in templates:
        command.extend(["--path", f"docs/{filename}"])
    result = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise PermissionError(f"A1 preflight 未通过：{detail}")


def main() -> int:
    """执行初始化并输出可审计的写入结果。"""
    args = parse_args()
    try:
        project_root = validate_project_root(args.project_root)
        templates = select_templates(args.include)
        run_preflight(
            project_root,
            args.work_item,
            args.ledger,
            args.object,
            templates,
        )
        written = initialize_documents(project_root, templates, args.force)
    except (OSError, ValueError) as error:
        print(f"初始化失败：{error}", file=sys.stderr)
        return 1

    print("已初始化项目交付物：")
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
